def _jsonl_records(path: Path) -> list[dict[str, Any]]:
    records: list[dict[str, Any]] = []
    for line_number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        if not line.strip():
            continue
        try:
            record = json.loads(line)
        except json.JSONDecodeError as error:
            raise VerificationError(f"invalid JSONL at {path}:{line_number}") from error
        if not isinstance(record, dict):
            raise VerificationError(f"invalid JSONL object at {path}:{line_number}")
        records.append(record)
    return records


def _csv_records(path: Path) -> list[dict[str, str]]:
    try:
        with path.open("r", encoding="utf-8", newline="") as handle:
            reader = csv.DictReader(handle)
            if reader.fieldnames is None:
                raise VerificationError(f"CSV has no header: {path}")
            return list(reader)
    except OSError as error:
        raise VerificationError(f"cannot read CSV: {path}") from error


def _check_counts(root: Path) -> tuple[dict[str, int], dict[str, int], dict[str, list[dict[str, Any]]]]:
    checked: dict[str, int] = {}
    checked_rows: dict[str, int] = {}
    records: dict[str, list[dict[str, Any]]] = {}
    for name, relative in COUNTED_ARTIFACTS.items():
        path = root / relative
        if path.suffix == ".jsonl":
            rows: list[dict[str, Any]] = _jsonl_records(path)
        else:
            rows = _csv_records(path)
        checked_rows[name] = len(rows)
        if checked_rows[name] != EXPECTED_ROW_COUNTS[name]:
            raise VerificationError(
                f"{name} expected {EXPECTED_ROW_COUNTS[name]} rows, found {checked_rows[name]} in {relative}"
            )
        checked[name] = (
            checked_rows[name] * W06_RATING_UNITS_PER_ROW
            if name == "week06_judge_ratings" else checked_rows[name]
        )
        records[name] = rows
    return checked, checked_rows, records


def _model_lock(root: Path) -> dict[str, str]:
    payload = _read_json(root / "week-10/W10_Reproducibility_Package/model_lock.json", "model lock")
    if payload.get("schema_version") != "ingen-model-lock-v1":
        raise VerificationError("unsupported model-lock schema")
    models = payload.get("models")
    if not isinstance(models, dict) or not models:
        raise VerificationError("model lock has no models")
    revisions: dict[str, str] = {}
    for model_id, spec in models.items():
        if not isinstance(spec, dict):
            raise VerificationError(f"invalid model lock entry: {model_id}")
        revision = spec.get("revision")
        if not isinstance(model_id, str) or not isinstance(revision, str) or not re.fullmatch(r"[0-9a-f]{40}", revision):
            raise VerificationError(f"model lock has mutable revision for {model_id}")
        revisions[model_id] = revision
    return revisions


def _check_model_pair(model_id: object, revision: object, lock: dict[str, str], location: str) -> tuple[str, str]:
    if not isinstance(model_id, str) or not model_id:
        raise VerificationError(f"missing model ID in {location}")
    if not isinstance(revision, str) or not revision:
        raise VerificationError(f"missing model revision in {location}")
    if lock.get(model_id) != revision:
        raise VerificationError(f"model revision does not match model_lock.json in {location}: {model_id}")
    return model_id, revision


def _check_model_metadata(payload: object, lock: dict[str, str], location: str, found: dict[str, str]) -> None:
    if isinstance(payload, list):
        for index, item in enumerate(payload):
            _check_model_metadata(item, lock, f"{location}[{index}]", found)
        return
    if not isinstance(payload, dict):
        return
    for id_key, revision_key in (
        ("model_id", "model_revision"),
        ("selected_model", "selected_model_revision"),
        ("preferred_model", "preferred_model_revision"),
        ("fallback_model", "fallback_model_revision"),
        ("generator_model", "generator_revision"),
        ("judge_model", "judge_revision"),
        ("id", "revision"),
    ):
        if id_key in payload:
            model_id, revision = _check_model_pair(payload[id_key], payload.get(revision_key), lock, location)
            found[model_id] = revision
    judge_revisions = payload.get("judge_revisions")
    if judge_revisions is not None:
        if not isinstance(judge_revisions, dict) or not judge_revisions:
            raise VerificationError(f"missing model revision in {location}.judge_revisions")
        for name, revision in judge_revisions.items():
            if not isinstance(revision, str) or revision not in lock.values():
                raise VerificationError(f"model revision does not match model_lock.json in {location}.judge_revisions[{name}]")
    for key, value in payload.items():
        if key != "judge_revisions":
            _check_model_metadata(value, lock, f"{location}.{key}", found)


def _require_row_fields(name: str, rows: list[dict[str, Any]], fields: tuple[str, ...]) -> None:
    for index, row in enumerate(rows, start=1):
        if any(not str(row.get(field, "")).strip() for field in fields):
            missing = next(field for field in fields if not str(row.get(field, "")).strip())
            raise VerificationError(f"{name} row {index} is missing required field: {missing}")


def _require_unique_keys(name: str, rows: list[dict[str, Any]], fields: tuple[str, ...]) -> None:
    _require_row_fields(name, rows, fields)
    seen: set[tuple[str, ...]] = set()
    for index, row in enumerate(rows, start=1):
        key = tuple(str(row[field]) for field in fields)
        if key in seen:
            raise VerificationError(f"{name} has duplicate logical key at row {index}: {', '.join(fields)}")
        seen.add(key)


